export function normalizeSearchText(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim();
}

const seenLabels = new Set<string>();

export const SMA_COLONIAS_CATALOG: SmaSettlement[] = RAW_SMA_SETTLEMENTS.reduce<SmaSettlement[]>(
  (acc, [name, type]) => {
    const label = `${name} - ${type}`;
    const dedupeKey = normalizeSearchText(label);
    if (!seenLabels.has(dedupeKey)) {
      seenLabels.add(dedupeKey);
      acc.push({
        name,
        type,
        label,
        searchKey: dedupeKey,
      });
    }
    return acc;
  },
  []
);

export const SMA_COLONIA_LABELS_SET = new Set(SMA_COLONIAS_CATALOG.map((item) => item.label));

export function filterSmaColonias(query: string, limit = 60): SmaSettlement[] {
  const normalizedQuery = normalizeSearchText(query);
  if (!normalizedQuery) {
    return SMA_COLONIAS_CATALOG.slice(0, limit);
  }

  const startsWithMatches: SmaSettlement[] = [];
  const containsMatches: SmaSettlement[] = [];

  for (const item of SMA_COLONIAS_CATALOG) {
    if (item.searchKey.startsWith(normalizedQuery)) {
      startsWithMatches.push(item);
    } else if (item.searchKey.includes(normalizedQuery)) {
      containsMatches.push(item);
    }
  }

  return [...startsWithMatches, ...containsMatches].slice(0, limit);
}

export function isValidSmaColoniaLabel(value: string): boolean {
  return SMA_COLONIA_LABELS_SET.has(value.trim());
}
